#!/usr/bin/env python3
"""Self-test of golden.py (the generator tripwire) on a scratch tree.

Copies a toy template into <tmp>/engines/x/coreml-templates/, then checks that
`update` + `check` pass and that `check` fails, with the right reason, when
the generated bytes change without a generator version bump, when the
version or the template changed, when a template has no entry and when an
entry names no template. Standard library only.

  test_golden.py --tool <qvac-coreml-tool> --toy <toy template dir>
"""

import argparse
import contextlib
import io
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import golden  # noqa: E402

ARGS = None


def run(cmd, root, gold):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        rc = golden.main([cmd, "--tool", ARGS.tool, "--root", str(root), "--golden", str(gold)])
    return rc, out.getvalue()


class GoldenTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="qvac-coreml-golden-test-"))
        self.rel = "engines/x/coreml-templates/" + Path(ARGS.toy).name
        shutil.copytree(ARGS.toy, self.tmp / self.rel)
        self.gold = self.tmp / "golden.txt"

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def entries(self):
        return golden.parse(self.gold.read_text())

    def write(self, entries):
        self.gold.write_text(golden.render(entries))

    def test_update_then_check_passes(self):
        self.assertEqual(run("update", self.tmp, self.gold)[0], 0)
        e = self.entries()
        self.assertEqual(list(e), [self.rel])
        self.assertEqual(len(e[self.rel][2]), 64)
        rc, out = run("check", self.tmp, self.gold)
        self.assertEqual(rc, 0, out)
        self.assertIn(f"ok {self.rel}", out)

    def test_changed_bytes_without_bump_fails(self):
        run("update", self.tmp, self.gold)
        v, t, _ = self.entries()[self.rel]
        self.write({self.rel: (v, t, "0" * 64)})
        rc, out = run("check", self.tmp, self.gold)
        self.assertEqual(rc, 1)
        self.assertIn("without a QVAC_COREML_GENERATOR_VERSION bump", out)

    def test_version_change_asks_for_update(self):
        run("update", self.tmp, self.gold)
        v, t, w = self.entries()[self.rel]
        self.write({self.rel: (v + 1, t, w)})
        rc, out = run("check", self.tmp, self.gold)
        self.assertEqual(rc, 1)
        self.assertIn(f"generator version {v}, golden.txt has {v + 1}: run golden.py update", out)

    def test_template_change_asks_for_update(self):
        run("update", self.tmp, self.gold)
        v, _, w = self.entries()[self.rel]
        self.write({self.rel: (v, "f" * 64, w)})
        rc, out = run("check", self.tmp, self.gold)
        self.assertEqual(rc, 1)
        self.assertIn("the template changed", out)

    def test_missing_entry_fails(self):
        self.write({})
        rc, out = run("check", self.tmp, self.gold)
        self.assertEqual(rc, 1)
        self.assertIn(f"{self.rel}: no golden entry", out)

    def test_stale_entry_fails(self):
        run("update", self.tmp, self.gold)
        e = self.entries()
        e["engines/x/coreml-templates/gone"] = e[self.rel]
        self.write(e)
        rc, out = run("check", self.tmp, self.gold)
        self.assertEqual(rc, 1)
        self.assertIn("gone: listed in golden.txt but not a template directory", out)

    def test_malformed_line_is_an_error(self):
        self.gold.write_text("engines/x/coreml-templates/a 1 abc\n")
        self.assertEqual(run("check", self.tmp, self.gold)[0], 2)


def main():
    global ARGS
    ap = argparse.ArgumentParser()
    ap.add_argument("--tool", required=True)
    ap.add_argument("--toy", required=True)
    ARGS, rest = ap.parse_known_args()
    unittest.main(argv=[sys.argv[0]] + rest, verbosity=2)


if __name__ == "__main__":
    main()
