#!/usr/bin/env python3
"""Generator tripwire: the weight.bin each template generates from its twin A.

engines/coreml/test/golden.txt has one line per Core ML template in the tree:

    <template dir, relative to the repository root> <generator_version> <template_sha256> <sha256(weight.bin)>

`check` regenerates every listed template's weight.bin from twin A
(`qvac-coreml-tool twin --manifest <dir>/reference-gguf.json --seed 1 --types f32`,
then `qvac-coreml-tool generate`) and compares. It fails when

  - the bytes changed while the generator version and the template did not:
    the generator's output changed without a QVAC_COREML_GENERATOR_VERSION
    bump (every cached artifact would silently keep the old bytes);
  - the generator version or the template changed: run `update` and commit
    golden.txt with the change;
  - a template under engines/*/coreml-templates/ has no line, or a line names
    a directory that does not exist.

`update` rewrites golden.txt from the current tree. Standard library only.
"""

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

SEED_A = 1
HEADER = """\
# Core ML generator tripwire: sha256 of the weight.bin each template generates
# from its twin A (reference-gguf.json, seed 1, f32). Regenerate with
#   python3 engines/coreml/python/golden.py update --tool <qvac-coreml-tool>
# A change of the generated bytes needs a QVAC_COREML_GENERATOR_VERSION bump.
#
# template_dir generator_version template_sha256 weight_bin_sha256
"""


class GoldenError(RuntimeError):
    pass


def tree_templates(root):
    root = Path(root)
    return sorted(str(p.parent.relative_to(root)) for p in root.glob("engines/*/coreml-templates/*/template.json"))


def parse(text):
    entries = {}
    for n, line in enumerate(text.splitlines(), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 4 or not parts[1].isdigit():
            raise GoldenError(f"golden.txt:{n}: expected `<dir> <generator_version> <template_sha256> <sha256>`")
        if parts[0] in entries:
            raise GoldenError(f"golden.txt:{n}: {parts[0]} is listed twice")
        entries[parts[0]] = (int(parts[1]), parts[2], parts[3])
    return entries


def render(entries):
    lines = [HEADER]
    for d in sorted(entries):
        v, t, w = entries[d]
        lines.append(f"{d} {v} {t} {w}\n")
    return "".join(lines)


def generate(tool, tdir):
    """(generator_version, template_sha256, sha256 of weight.bin) for twin A of `tdir`."""
    tdir = Path(tdir)
    manifest = tdir / "reference-gguf.json"
    if not manifest.is_file():
        raise GoldenError(f"{tdir}: no reference-gguf.json (twin A needs it)")
    with tempfile.TemporaryDirectory(prefix="qvac-coreml-golden-") as tmp:
        twin = Path(tmp) / "twin-a.gguf"
        p = subprocess.run([tool, "twin", "--manifest", str(manifest), "--seed", str(SEED_A), "--types", "f32",
                            "-o", str(twin)], capture_output=True, text=True)
        if p.returncode != 0:
            raise GoldenError(f"{tdir}: twin failed: {p.stderr.strip()}")
        pkg = Path(tmp) / "gen.mlpackage"
        p = subprocess.run([tool, "generate", "--template", str(tdir), "--gguf", str(twin), "-o", str(pkg)],
                           capture_output=True, text=True)
        if p.returncode != 0:
            raise GoldenError(f"{tdir}: generate failed: {p.stderr.strip()}")
        j = json.loads(p.stdout)
        wb = (pkg / "Data" / "com.apple.CoreML" / "weights" / "weight.bin").read_bytes()
        digest = hashlib.sha256(wb).hexdigest()
        if digest != j["weight_bin_sha256"]:
            raise GoldenError(f"{tdir}: the tool reported {j['weight_bin_sha256']} for a weight.bin hashing to {digest}")
        return int(j["generator_version"]), j["template_sha256"], digest


def check(tool, root, golden_path):
    root = Path(root)
    entries = parse(Path(golden_path).read_text())
    problems = []
    present = tree_templates(root)
    for d in present:
        if d not in entries:
            problems.append(f"{d}: no golden entry (run golden.py update)")
    for d, (v, tsha, wsha) in sorted(entries.items()):
        tdir = root / d
        if not (tdir / "template.json").is_file():
            problems.append(f"{d}: listed in golden.txt but not a template directory")
            continue
        gv, gt, gw = generate(tool, tdir)
        if gw == wsha and gv == v and gt == tsha:
            print(f"ok {d}")
            continue
        if gv != v:
            problems.append(f"{d}: generator version {gv}, golden.txt has {v}: run golden.py update")
        elif gt != tsha:
            problems.append(f"{d}: the template changed ({gt[:16]}, golden.txt has {tsha[:16]}): run golden.py update")
        else:
            problems.append(f"{d}: weight.bin {gw[:16]} != golden {wsha[:16]} with the same generator version {v} "
                            "and template: the generator's output changed without a "
                            "QVAC_COREML_GENERATOR_VERSION bump")
    for p in problems:
        print(f"FAIL {p}")
    print(f"golden: {len(entries)} template(s), {'FAIL' if problems else 'PASS'}")
    return 1 if problems else 0


def update(tool, root, golden_path):
    root = Path(root)
    entries = {d: generate(tool, root / d) for d in tree_templates(root)}
    Path(golden_path).write_text(render(entries))
    print(f"golden: wrote {len(entries)} template(s) to {golden_path}")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=("check", "update"))
    ap.add_argument("--tool", required=True, help="qvac-coreml-tool")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[3]), help="repository root")
    ap.add_argument("--golden", help="golden.txt (default: <root>/engines/coreml/test/golden.txt)")
    a = ap.parse_args(argv)
    golden = a.golden or str(Path(a.root) / "engines" / "coreml" / "test" / "golden.txt")
    try:
        return check(a.tool, a.root, golden) if a.cmd == "check" else update(a.tool, a.root, golden)
    except GoldenError as e:
        print(f"golden: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
